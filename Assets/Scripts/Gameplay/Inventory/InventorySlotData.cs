using System;
using Rapadura.Gameplay.Items;

namespace Rapadura.Gameplay.Inventory
{
    /// <summary>
    /// A single inventory slot's runtime state. Stores only the item id (not a direct asset
    /// reference) plus quantity/durability, so this class serializes cleanly to JSON — the
    /// actual <see cref="ItemDefinition"/> is resolved through <see cref="ItemDatabase"/>.
    /// </summary>
    [Serializable]
    public class InventorySlotData
    {
        public string itemId;
        public int quantity;
        public float currentDurability;

        // Optional procedural-affix data (Fase 3 — "Sistema de geração procedural de itens").
        // Populated only for items generated via ProceduralItemGenerator (Rare/Epic/Legendary
        // rolls); left null/empty for plain (non-generated) items so existing saves and code
        // that only ever touched itemId/quantity/currentDurability are unaffected. Stored as
        // parallel primitive arrays (affix id + rolled value), not a direct reference to
        // Items.Procedural.GeneratedItemInstance, because this class must stay JSON-serializable
        // via JsonUtility for SaveManager and GeneratedItemInstance is a plain runtime object
        // that resolves its affixes through AffixDatabase — only the ids/values need to persist.
        public string[] generatedAffixIds;
        public float[] generatedAffixValues;
        public string generatedName;

        // Rarity the item was rolled at by ProceduralItemGenerator. Only meaningful when
        // HasGeneratedAffixes is true (base items use ItemDefinition.Rarity). Old saves without
        // this field deserialize to Common, and display code takes the max of this and the base
        // item's rarity, so they keep showing the base rarity.
        public ItemRarity generatedRarity;

        public bool IsEmpty => string.IsNullOrEmpty(itemId) || quantity <= 0;

        /// <summary>True if this slot holds an item generated by ProceduralItemGenerator (has rolled affixes).</summary>
        public bool HasGeneratedAffixes => generatedAffixIds != null && generatedAffixIds.Length > 0;

        /// <summary>
        /// True if this slot carries ANY procedurally-generated data (affixes, a generated name or a
        /// rolled rarity above Common). Broader than <see cref="HasGeneratedAffixes"/> on purpose:
        /// a roll can legitimately come out with zero affixes but still a generated name/rarity, and
        /// code that decides whether a slot may be stacked/merged with a plain item of the same id
        /// must not treat that as a plain item (merging would silently drop the generated data).
        /// </summary>
        public bool HasGeneratedData =>
            HasGeneratedAffixes || !string.IsNullOrEmpty(generatedName) || generatedRarity != ItemRarity.Common;

        /// <summary>
        /// Copies only the procedural fields (affix ids/values, generated name, generated rarity)
        /// from <paramref name="source"/>, leaving itemId/quantity/durability untouched. Arrays are
        /// cloned so the two slots never share (and later mutate) the same array instance.
        /// </summary>
        public void CopyGeneratedDataFrom(InventorySlotData source)
        {
            generatedAffixIds = source?.generatedAffixIds != null ? (string[])source.generatedAffixIds.Clone() : null;
            generatedAffixValues = source?.generatedAffixValues != null ? (float[])source.generatedAffixValues.Clone() : null;
            generatedName = source?.generatedName;
            generatedRarity = source != null ? source.generatedRarity : ItemRarity.Common;
        }

        /// <summary>Deep copy of this slot (including generated data) with an explicit quantity.</summary>
        public InventorySlotData CloneWithQuantity(int newQuantity)
        {
            var copy = new InventorySlotData
            {
                itemId = itemId,
                quantity = newQuantity,
                currentDurability = currentDurability,
            };
            copy.CopyGeneratedDataFrom(this);
            return copy;
        }

        public static InventorySlotData Empty()
        {
            return new InventorySlotData { itemId = null, quantity = 0, currentDurability = 0f };
        }

        public void Clear()
        {
            itemId = null;
            quantity = 0;
            currentDurability = 0f;
            generatedAffixIds = null;
            generatedAffixValues = null;
            generatedName = null;
            generatedRarity = ItemRarity.Common;
        }
    }
}
